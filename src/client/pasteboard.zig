//! The macOS pasteboard, as the user's clipboard (see `clipboard`).
//!
//! AppKit and the Objective-C runtime are loaded when the client starts,
//! rather than linked: tx for macOS is built on Linux too, where there are
//! no macOS frameworks to link against. Calls go through `objc_msgSend`,
//! cast to each method's signature, as arm64 requires.
//!
//! Types, as programs on the host ask for them:
//!
//! - Text (`public.utf8-plain-text`) is offered as `text/plain`,
//!   `text/plain;charset=utf-8`, `UTF8_STRING`, `TEXT` and `STRING`, the
//!   names X11 and Wayland programs look for.
//! - An image is offered as `image/png`. A screenshot is often on the
//!   pasteboard as TIFF only (`public.tiff`), and is converted to PNG when
//!   read. Without that, Claude Code finds no image.
//! - Nothing is offered while the pasteboard is marked concealed,
//!   transient or auto-generated (`org.nspasteboard.ConcealedType` and so
//!   on), as password managers mark what they copy.
const std = @import("std");
const builtin = @import("builtin");
const Allocator = std.mem.Allocator;
const clipboard = @import("clipboard.zig");

const log = std.log.scoped(.pasteboard);

/// An Objective-C object, class or selector.
const Id = *opaque {};
const Sel = *opaque {};

const utf8_text = "public.utf8-plain-text";
const png = "public.png";
const tiff = "public.tiff";

/// What text is offered as.
const text_mimes = [_][]const u8{ "text/plain;charset=utf-8", "text/plain", "UTF8_STRING", "TEXT", "STRING" };

/// Types that mean the pasteboard holds something not to share.
const private_types = [_][]const u8{
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
};

/// `NSUTF8StringEncoding`.
const utf8_encoding: usize = 4;
/// `NSBitmapImageFileTypePNG`.
const png_file_type: usize = 4;

pub const Pasteboard = struct {
    rt: Runtime,
    /// The `NSPasteboard`.
    board: Id,

    /// The general pasteboard, the one Cmd-C and Cmd-V use. Null where
    /// AppKit can't be loaded.
    pub fn general() ?Pasteboard {
        const rt = Runtime.load() orelse return null;
        const pool = rt.push();
        defer rt.pop(pool);
        const class = rt.class("NSPasteboard") orelse return null;
        const board = rt.call(?Id, class, "generalPasteboard", .{}) orelse return null;
        return .{ .rt = rt, .board = rt.call(Id, board, "retain", .{}) };
    }

    /// A pasteboard of its own, for tests.
    fn named(name: []const u8) ?Pasteboard {
        const rt = Runtime.load() orelse return null;
        const pool = rt.push();
        defer rt.pop(pool);
        const class = rt.class("NSPasteboard") orelse return null;
        const board = rt.call(?Id, class, "pasteboardWithName:", .{rt.stringOwned(name) orelse return null}) orelse return null;
        return .{ .rt = rt, .board = rt.call(Id, board, "retain", .{}) };
    }

    pub fn provider(p: *Pasteboard) clipboard.Provider {
        return .{ .context = p, .change = change, .types = types, .read = read, .write = write };
    }

    fn of(context: ?*anyopaque) *Pasteboard {
        return @ptrCast(@alignCast(context.?));
    }

    fn change(context: ?*anyopaque) u64 {
        const p = of(context);
        return @bitCast(p.rt.call(isize, p.board, "changeCount", .{}));
    }

    fn types(context: ?*anyopaque, gpa: Allocator) Allocator.Error![]u8 {
        const p = of(context);
        const rt = p.rt;
        const pool = rt.push();
        defer rt.pop(pool);

        var has_text = false;
        var has_image = false;
        const list = rt.call(?Id, p.board, "types", .{}) orelse return gpa.dupe(u8, "");
        const count = rt.call(usize, list, "count", .{});
        for (0..count) |i| {
            const name = rt.utf8(rt.call(Id, list, "objectAtIndex:", .{i})) orelse continue;
            for (private_types) |private| if (std.mem.eql(u8, name, private)) return gpa.dupe(u8, "");
            if (std.mem.eql(u8, name, utf8_text)) has_text = true;
            if (std.mem.eql(u8, name, png) or std.mem.eql(u8, name, tiff)) has_image = true;
        }

        var out: std.ArrayList(u8) = .empty;
        errdefer out.deinit(gpa);
        // An image first: a program that takes either takes it, as it
        // would locally.
        if (has_image) try out.appendSlice(gpa, "image/png\x00");
        if (has_text) for (text_mimes) |m| {
            try out.appendSlice(gpa, m);
            try out.append(gpa, 0);
        };
        return out.toOwnedSlice(gpa);
    }

    fn read(context: ?*anyopaque, gpa: Allocator, mime: []const u8) Allocator.Error!?[]u8 {
        const p = of(context);
        const rt = p.rt;
        const pool = rt.push();
        defer rt.pop(pool);

        if (isText(mime)) {
            const text = rt.call(?Id, p.board, "stringForType:", .{rt.string(utf8_text) orelse return null}) orelse return null;
            return try gpa.dupe(u8, rt.utf8(text) orelse return null);
        }
        if (!std.mem.eql(u8, mime, "image/png")) return null;

        if (rt.call(?Id, p.board, "dataForType:", .{rt.string(png) orelse return null})) |data| return try rt.bytes(gpa, data);

        // TIFF, as PNG.
        const data = rt.call(?Id, p.board, "dataForType:", .{rt.string(tiff) orelse return null}) orelse return null;
        const class = rt.class("NSBitmapImageRep") orelse return null;
        const image = rt.call(?Id, class, "imageRepWithData:", .{data}) orelse return null;
        const properties = rt.call(Id, rt.class("NSDictionary") orelse return null, "dictionary", .{});
        const converted = rt.call(?Id, image, "representationUsingType:properties:", .{ png_file_type, properties }) orelse return null;
        return try rt.bytes(gpa, converted);
    }

    fn write(context: ?*anyopaque, items: []const clipboard.Item) u64 {
        const p = of(context);
        const rt = p.rt;
        const pool = rt.push();
        defer rt.pop(pool);

        _ = rt.call(isize, p.board, "clearContents", .{});
        var wrote_text = false;
        for (items) |item| {
            if (isText(item.mime)) {
                // The first text type stands for them all.
                if (wrote_text) continue;
                const text = rt.stringOwned(item.data) orelse continue;
                _ = rt.call(bool, p.board, "setString:forType:", .{ text, rt.string(utf8_text) orelse continue });
                wrote_text = true;
            } else if (std.mem.eql(u8, item.mime, "image/png")) {
                const data = rt.call(Id, rt.class("NSData") orelse continue, "dataWithBytes:length:", .{ item.data.ptr, item.data.len });
                _ = rt.call(bool, p.board, "setData:forType:", .{ data, rt.string(png) orelse continue });
            }
        }
        return @bitCast(rt.call(isize, p.board, "changeCount", .{}));
    }

    fn isText(mime: []const u8) bool {
        for (text_mimes) |m| if (std.mem.eql(u8, m, mime)) return true;
        return false;
    }
};

/// The Objective-C runtime's functions, from libobjc, with AppKit loaded
/// so that its classes are registered.
const Runtime = struct {
    getClass: *const fn ([*:0]const u8) callconv(.c) ?Id,
    registerName: *const fn ([*:0]const u8) callconv(.c) Sel,
    msgSend: *const anyopaque,
    poolPush: *const fn () callconv(.c) ?*anyopaque,
    poolPop: *const fn (?*anyopaque) callconv(.c) void,

    fn load() ?Runtime {
        if (!builtin.os.tag.isDarwin()) return null;
        const flags: std.c.RTLD = .{ .LAZY = true, .GLOBAL = true };
        const objc = std.c.dlopen("/usr/lib/libobjc.A.dylib", flags) orelse return failed("libobjc");
        _ = std.c.dlopen("/System/Library/Frameworks/AppKit.framework/AppKit", flags) orelse return failed("AppKit");
        return .{
            .getClass = @ptrCast(@alignCast(std.c.dlsym(objc, "objc_getClass") orelse return failed("objc_getClass"))),
            .registerName = @ptrCast(@alignCast(std.c.dlsym(objc, "sel_registerName") orelse return failed("sel_registerName"))),
            .msgSend = std.c.dlsym(objc, "objc_msgSend") orelse return failed("objc_msgSend"),
            .poolPush = @ptrCast(@alignCast(std.c.dlsym(objc, "objc_autoreleasePoolPush") orelse return failed("objc_autoreleasePoolPush"))),
            .poolPop = @ptrCast(@alignCast(std.c.dlsym(objc, "objc_autoreleasePoolPop") orelse return failed("objc_autoreleasePoolPop"))),
        };
    }

    fn failed(what: []const u8) ?Runtime {
        log.warn("can't load {s}, so the clipboard isn't shared", .{what});
        return null;
    }

    /// Objects the calls between `push` and `pop` make are released at
    /// `pop`.
    fn push(rt: Runtime) ?*anyopaque {
        return rt.poolPush();
    }

    fn pop(rt: Runtime, pool: ?*anyopaque) void {
        rt.poolPop(pool);
    }

    fn class(rt: Runtime, name: [:0]const u8) ?Id {
        return rt.getClass(name);
    }

    /// Sends `selector` to `target` with `args`: `objc_msgSend` called as
    /// a function of exactly these types.
    fn call(rt: Runtime, comptime Ret: type, target: Id, comptime selector: [:0]const u8, args: anytype) Ret {
        const types_ = @typeInfo(@TypeOf(args)).@"struct".field_types;
        const sel = rt.registerName(selector);
        switch (types_.len) {
            0 => {
                const f: *const fn (Id, Sel) callconv(.c) Ret = @ptrCast(@alignCast(rt.msgSend));
                return f(target, sel);
            },
            1 => {
                const f: *const fn (Id, Sel, types_[0]) callconv(.c) Ret = @ptrCast(@alignCast(rt.msgSend));
                return f(target, sel, args[0]);
            },
            2 => {
                const f: *const fn (Id, Sel, types_[0], types_[1]) callconv(.c) Ret = @ptrCast(@alignCast(rt.msgSend));
                return f(target, sel, args[0], args[1]);
            },
            else => @compileError("more arguments than any call here takes"),
        }
    }

    /// An `NSString` of a constant, autoreleased.
    fn string(rt: Runtime, comptime text: []const u8) ?Id {
        return rt.stringOwned(text);
    }

    /// An `NSString` of UTF-8 bytes, autoreleased.
    fn stringOwned(rt: Runtime, text: []const u8) ?Id {
        const class_ = rt.class("NSString") orelse return null;
        const allocated = rt.call(Id, class_, "alloc", .{});
        const s = rt.call3(?Id, allocated, "initWithBytes:length:encoding:", text.ptr, text.len, utf8_encoding) orelse return null;
        return rt.call(Id, s, "autorelease", .{});
    }

    fn call3(rt: Runtime, comptime Ret: type, target: Id, comptime selector: [:0]const u8, a: [*]const u8, b: usize, c: usize) Ret {
        const f: *const fn (Id, Sel, [*]const u8, usize, usize) callconv(.c) Ret = @ptrCast(@alignCast(rt.msgSend));
        return f(target, rt.registerName(selector), a, b, c);
    }

    /// An `NSString`'s UTF-8, valid until the pool is popped.
    fn utf8(rt: Runtime, s: Id) ?[]const u8 {
        const ptr = rt.call(?[*:0]const u8, s, "UTF8String", .{}) orelse return null;
        return std.mem.span(ptr);
    }

    /// An `NSData`'s bytes, copied.
    fn bytes(rt: Runtime, gpa: Allocator, data: Id) Allocator.Error![]u8 {
        const len = rt.call(usize, data, "length", .{});
        if (len == 0) return gpa.dupe(u8, "");
        const ptr = rt.call(?[*]const u8, data, "bytes", .{}) orelse return gpa.dupe(u8, "");
        return gpa.dupe(u8, ptr[0..len]);
    }
};

const testing = std.testing;

test "text and images go on the pasteboard and come back as programs ask for them" {
    var p = Pasteboard.named("tx-test") orelse return error.SkipZigTest;
    const provider = p.provider();

    const before = provider.change(provider.context);
    const after = provider.write(provider.context, &.{
        .{ .mime = "text/plain", .data = "from a program" },
        .{ .mime = "UTF8_STRING", .data = "ignored" },
    });
    try testing.expect(after != before);
    try testing.expectEqual(after, provider.change(provider.context));

    const offered = try provider.types(provider.context, testing.allocator);
    defer testing.allocator.free(offered);
    try testing.expectEqualStrings("text/plain;charset=utf-8\x00text/plain\x00UTF8_STRING\x00TEXT\x00STRING\x00", offered);

    const text = (try provider.read(provider.context, testing.allocator, "STRING")).?;
    defer testing.allocator.free(text);
    try testing.expectEqualStrings("from a program", text);
    try testing.expectEqual(null, try provider.read(provider.context, testing.allocator, "image/png"));

    // A PNG of one pixel.
    const pixel = [_]u8{
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4,
        0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0xf8, 0xcf, 0xc0, 0xf0,
        0x1f, 0x00, 0x05, 0x00, 0x01, 0xff, 0x89, 0x99, 0x3d, 0x1d, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
        0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    };
    _ = provider.write(provider.context, &.{.{ .mime = "image/png", .data = &pixel }});
    const image = (try provider.read(provider.context, testing.allocator, "image/png")).?;
    defer testing.allocator.free(image);
    try testing.expectEqualSlices(u8, &pixel, image);
}
