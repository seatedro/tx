//! Writes the Zig source that lists a release's txd builds with their
//! SHA-256, which tx checks a txd against before copying it to a host.
//!
//! Usage: txd_builds OUT [OS ARCH PATH]...
const std = @import("std");
const Io = std.Io;
const Sha256 = std.crypto.hash.sha2.Sha256;

pub fn main(init: std.process.Init) !void {
    const gpa = init.gpa;
    const io = init.io;
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len < 2 or (args.len - 2) % 3 != 0) return error.Usage;

    var out: Io.Writer.Allocating = .init(gpa);
    defer out.deinit();
    const w = &out.writer;
    try w.writeAll(
        \\//! Generated by src/build/txd_builds.zig.
        \\pub const Build = struct {
        \\    /// `builtin.os.tag` and `builtin.cpu.arch` of the build.
        \\    os: []const u8,
        \\    arch: []const u8,
        \\    sha256_hex: *const [64]u8,
        \\};
        \\
        \\pub const builds = [_]Build{
        \\
    );

    var i: usize = 2;
    while (i < args.len) : (i += 3) {
        const bytes = try Io.Dir.cwd().readFileAlloc(io, args[i + 2], gpa, .limited(256 << 20));
        defer gpa.free(bytes);
        var digest: [Sha256.digest_length]u8 = undefined;
        Sha256.hash(bytes, &digest, .{});
        try w.print("    .{{ .os = \"{s}\", .arch = \"{s}\", .sha256_hex = \"{s}\" }},\n", .{ args[i], args[i + 1], std.fmt.bytesToHex(digest, .lower) });
    }
    try w.writeAll("};\n");

    try Io.Dir.cwd().writeFile(io, .{ .sub_path = args[1], .data = out.written() });
}
